# Label-free drop list: everything TMT-specific.
_TMT_TOKENS = ("304.207", "304.2070")


def build_params(fasta: str, threads: int, label: str) -> str:
    """Return the MSFragger parameter file text.

    Parameters
    ----------
    fasta : str
        Path to the target+decoy FASTA.
    threads : int
        MSFragger worker threads.
    label : str
        'tmt16' keeps the TMTpro modifications; 'label-free' drops them.

    Returns
    -------
    str
        Parameter file content.
    """
    params = dict(PAPER_PARAMS)
    if label == "label-free":
        for key, value in list(params.items()):
            if key.startswith("variable_mod") or key.startswith("add_"):
                if any(tok in value for tok in _TMT_TOKENS):
                    params.pop(key)
    params["database_name"] = fasta
    params["num_threads"] = str(threads)

    lines = [
        "# MSFragger parameter file generated by make_fragger_params.py",
        "# Method source: PXD053575 / Blood 2025;147(23):2809 (MSFragger 3.5)",
        "",
    ]
    for key in sorted(params):
        lines.append(f"{key} = {params[key]}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fasta", required=True, help="target+decoy FASTA")
    parser.add_argument("-o", "--out", required=True, help="output parameter file")
    parser.add_argument("-t", "--threads", type=int, default=16, help="MSFragger threads (default 16)")
    parser.add_argument("-l", "--label", default="tmt16",
                        choices=["tmt16", "label-free"],
                        help="label chemistry (default tmt16, paper method)")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s")
    if not os.path.exists(args.fasta):
        logger.error("FASTA not found: %s", args.fasta)
        sys.exit(1)

    text = build_params(args.fasta, args.threads, args.label)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    tmp = args.out + ".tmp"
    with open(tmp, "w") as handle:
        handle.write(text)
    os.replace(tmp, args.out)
    logger.info("wrote %s (label=%s, threads=%d)", args.out, args.label, args.threads)


if __name__ == "__main__":
    main()
