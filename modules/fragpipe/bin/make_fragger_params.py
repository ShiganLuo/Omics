#!/usr/bin/env python3
"""Generate an MSFragger parameter file following the PXD053575 paper method.

The defaults reproduce the parameter dump recovered from the original
pepXML files (MSFragger 3.5, Blood 2025;147(23):2809, PXD053575):
mass calibration on, precursor -20/+20 ppm CORRECTED, fragment 0.02 Da,
strict trypsin with 2 missed cleavages, TMTpro fixed on K and variable on
any N-term, carbamidomethyl fixed on C, oxidation/pyro-glu variable mods.

Usage:
    python make_fragger_params.py --fasta db.fasta -o fragger.params
    python make_fragger_params.py --fasta db.fasta -o fragger.params \
        --threads 16 --label tmt16

Parameters
----------
--fasta PATH      Target+decoy FASTA the search runs against (required).
-o/--out PATH     Output parameter file (required).
--threads N       MSFragger threads (default 16).
--label STR       tmt16 (default, paper method) or label-free (drops the
                  TMTpro fixed/variable modifications).
"""
from __future__ import annotations

import argparse
import logging
import os
import sys
from typing import Dict, List

logger = logging.getLogger("make_fragger_params")


# Parameter values recovered from the original pepXML (PXD053575) dumps.
